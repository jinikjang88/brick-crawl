def brick(kind):
    c = Cv(44, 24)
    c.rect(0, 0, 43, 23, LINE)
    if kind == 'n':          # 데이터 블록: 티타늄 판 + 가로 홈 + 오른쪽 상태등
        bevel(c, 1, 1, 42, 22, TI[1], TI[3], TI[0])
