def coin():     # 크레딧: 팔각 티타늄 토큰 + 가운데 상아 마름모
    c = Cv(16, 16)
    for y in range(16):
        for x in range(16):
            dx, dy = abs(x - 7.5), abs(y - 7.5)
            if max(dx, dy) <= 6.5 and dx + dy <= 9.5:
                edge = max(dx, dy) > 5 or dx + dy > 8
                c.put(x, y, (TI[3] if x + y < 15 else TI[1]) if edge else GM[2])
    for x, y in ((7, 5), (8, 5), (6, 6), (9, 6), (5, 7), (10, 7), (5, 8), (10, 8), (6, 9), (9, 9), (7, 10), (8, 10)):
        c.put(x, y, IV[3])
    c.rect(7, 7, 8, 8, IV[4])
    c.outline()
    return c


