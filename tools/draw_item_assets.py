class Cv:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.px = [[None] * w for _ in range(h)]

    def put(self, x, y, c):
        x, y = int(x), int(y)
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[y][x] = c

    def get(self, x, y):
        return self.px[y][x] if 0 <= x < self.w and 0 <= y < self.h else None

    def rect(self, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.put(x, y, c)

    def line(self, x0, y0, x1, y1, c):
        n = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(n + 1):
            self.put(round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n), c)

    def sphere(self, cx, cy, r, ramp, lo=0.0):
        """왼쪽 위 광원의 구면 명암을 램프 단계로 끊어 칠한다. lo를 올리면 전체가 밝아진다."""
        for y in range(int(cy - r) - 1, int(cy + r) + 2):
            for x in range(int(cx - r) - 1, int(cx + r) + 2):
                nx, ny = (x + .5 - cx) / r, (y + .5 - cy) / r
                d = nx * nx + ny * ny
                if d > 1:
                    continue
                nz = math.sqrt(1 - d)
                k = max(0, nx * -.55 + ny * -.62 + nz * .56) + lo
                self.put(x, y, ramp[max(0, min(len(ramp) - 1, int(k * len(ramp))))])

    def glyph(self, x0, y0, rows, remap=None):
        for j, row in enumerate(rows):
            for i, ch in enumerate(row):
                if ch != '.':
                    self.put(x0 + i, y0 + j, (remap or INK)[ch])

    def outline(self, c=LINE):
        add = []
        for y in range(self.h):
            for x in range(self.w):
                if self.px[y][x] is None and any(self.get(x + dx, y + dy) is not None for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    add.append((x, y))
        for x, y in add:
            self.px[y][x] = c

    def image(self, scale):
        im = Image.new('RGBA', (self.w, self.h), (0, 0, 0, 0))
        for y in range(self.h):
            for x in range(self.w):
                if self.px[y][x] is not None:
                    im.putpixel((x, y), self.px[y][x] + (255,))
        return im.resize((self.w * scale, self.h * scale), Image.NEAREST)


def save(cv, name, scale, out=OUT):
    out.mkdir(parents=True, exist_ok=True)
    p = out / f'{name}.png'
    cv.image(scale).save(p, optimize=True)
    return p


def G(text):
    rows = text.strip().split('\n')
    assert len(rows) == 11 and all(len(r) == 11 for r in rows), f'문양은 11×11이어야 한다:\n{text}'
    return rows


# ── 코어 7종: 전투에서 날아가는 구슬 자체. 실루엣만으로 움직임 규칙이 읽히게 한다 ─────────────
def core_basic():   # 번개: 매끈한 상아 구 + 적도 이음매 + 번개 접점
    c = Cv(32, 32); c.sphere(16, 16, 11, IV)
    for x in range(6, 27):
        if c.get(x, 18) is not None:
            c.put(x, 18, TI[1])
    for x, y in ((17, 9), (16, 10), (15, 11), (14, 12), (15, 12), (16, 12), (17, 12), (16, 13), (15, 14), (14, 15)):
        c.put(x, y, GM[1])
    return c


def core_drill():   # 관통: 나선 홈이 감긴 구 + 오른쪽 위로 뻗은 드릴 끝
    c = Cv(32, 32); c.sphere(14, 18, 10, TI)
    for k in range(-14, 16, 5):
        for x in range(4, 25):
            y = x + k
            if c.get(x, y) is not None and (x - 14) ** 2 + (y - 18) ** 2 < 90:
                c.put(x, y, GM[2])
    for i in range(8):   # 원뿔: 뿌리가 굵고 끝이 뾰족하다
        wdt = (7 - i) // 2
        for t in range(-wdt, wdt + 1):
            col = IV[4] if t < 0 else IV[2] if t == 0 else TI[1]
            c.put(20 + i + t, 11 - i + t, col); c.put(21 + i + t, 11 - i + t, col)   # 대각선 격자의 빈칸을 메운다
    return c


def core_bomb():    # EMP: 어두운 구 + 적도에 두른 축전기 고리 + 위의 붉은 충전등
    c = Cv(32, 32); c.sphere(16, 17, 11, GM, .12)
    for x in (6, 10, 14, 18, 22):
        c.rect(x, 16, x + 2, 19, TI[2]); c.rect(x, 16, x + 2, 16, TI[4]); c.put(x + 2, 19, TI[0])
    c.rect(15, 4, 17, 6, RED); c.put(15, 4, (232, 150, 140)); c.put(17, 6, RED_D)
    return c


def core_magnet():  # 전자석: 상아 구를 아래에서 문 U자 자석, 양 끝이 빛난다
    c = Cv(32, 32)
    for y in range(32):
        for x in range(32):
            d = math.hypot(x + .5 - 16, y + .5 - 14)
            if 10.2 <= d <= 13.6 and y >= 14:
                c.put(x, y, GM[3] if x < 14 else GM[2] if x < 20 else GM[1])
    c.rect(2, 11, 5, 13, GLOW); c.rect(26, 11, 29, 13, GLOW)
    c.sphere(16, 13, 8.5, IV)
    return c


def core_heavy():   # 텅스텐: 다른 코어보다 큰 리벳 박힌 장갑 구
    c = Cv(32, 32); c.sphere(16, 16, 13.5, GM, .1)
    for i in range(3, 30):
        for x, y in ((i, 16), (16, i), (i, 9), (i, 23)):
            if c.get(x, y) is not None and (x - 16) ** 2 + (y - 16) ** 2 < 150:
                c.put(x, y, LINE)
    for x, y in ((9, 6), (22, 6), (6, 12), (25, 12), (6, 20), (25, 20), (11, 26), (20, 26), (12, 12), (20, 19)):
        if c.get(x, y) is not None:
            c.put(x, y, TI[3])
    return c


def core_split():   # 분광: 세 조각 렌즈가 Y자 이음매로 갈라지려 한다
    c = Cv(32, 32); c.sphere(16, 16, 11, TI)
    for y in range(32):
        for x in range(32):
            dx, dy = x + .5 - 16, y + .5 - 16
            d = math.hypot(dx, dy)
            if d > 8.4 or c.get(x, y) is None:
                continue
            a = (math.degrees(math.atan2(dy, dx)) + 360 + 90) % 360
            near = min(a % 120, 120 - a % 120)
            if near * d / 57.3 < .8 or d < 1.2:
                c.put(x, y, LINE)
            else:
                c.put(x, y, IV[4] if a < 120 and dx < 0 else IV[3] if a > 240 else IV[2] if a < 120 else IV[1])
    return c


def core_comet():   # 아크: 가장 밝은 구 + 방전 고리 + 오른쪽 위로 끌리는 꼬리
    c = Cv(32, 32)
    for i in range(12):
        wdt = max(0, 4 - i // 3)
        for t in range(-wdt, wdt + 1):
            col = TI[2] if abs(t) == wdt else TI[4]
            c.put(17 + i + t, 13 - i + t, col); c.put(18 + i + t, 13 - i + t, col)
    c.sphere(13, 19, 9, IV, .22)
    c.outline(); c.sealed = True   # 방전 고리의 점은 빛이라 외곽선을 두르지 않는다
    for a in range(0, 360, 6):
        if a % 60 < 34:
            c.put(13.5 + math.cos(math.radians(a)) * 11.6, 19.5 + math.sin(math.radians(a)) * 11.6, GLOW)
    return c


