def bevel(c, x0, y0, x1, y1, face, hi, lo):
    c.rect(x0, y0, x1, y1, face)
    c.rect(x0, y0, x1, y0, hi); c.rect(x0, y0, x0, y1, hi)
    c.rect(x0, y1, x1, y1, lo); c.rect(x1, y0, x1, y1, lo)


def circuit(rows):
    c = Cv(32, 32)
    bevel(c, 6, 3, 25, 23, TI[1], TI[3], TI[0])
    c.rect(8, 5, 23, 21, GM[1]); c.rect(8, 5, 23, 5, GM[0]); c.rect(8, 5, 8, 21, GM[0])
    # 오른쪽 위 모서리를 깎아 꽂는 방향을 표시한다
    for i in range(3):
        for j in range(3 - i):
            c.px[3 + i][25 - j] = None
    # 아래 단자: 밝은 접점과 어두운 틈이 번갈아
    c.rect(8, 24, 23, 28, GM[2])
    for x in range(9, 23, 2):
        c.rect(x, 25, x, 28, TI[4])
    c.glyph(11, 8, rows)
    c.outline()
    return c


