        for x, y in (((23, 2), (26, 3)), ((21, 3), (24, 1)), ((25, 2), (22, 4)))[f]:
            c.put(x, y, GLOW)                              # 접점 위의 작은 불티(외곽선 없이)
        sheet.paste(c.image(4), (f * W * 4, 0))
